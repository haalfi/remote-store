"""Generate the sync contract kernel from the async one (RFC-0017 D6, BK-389).

The kernel is written once, in async, under ``src/remote_store/_kernel/_async/``.
This script derives ``_sync/driver.py`` and ``_sync/kernel.py`` from it with
``unasync``'s token pass: ``async``/``await`` dropped, async names mapped to
their sync twins. Then it orders imports and formats with ruff, because
dropping ``await`` shortens lines that ruff would otherwise re-join, and
renaming imports reorders them. ``_sync/_io.py`` is hand-written, as are
``_kernel/backend.py`` and ``aio_backend.py``, which hold what the runtimes do
not share.

    hatch run gen-sync-kernel          # regenerate
    hatch run gen-sync-kernel-check    # exit 1 if a generated file is stale

The comparison is on LF-normalised text, as the other ``gen_*`` checks do.
The generated files are edit-free: a hand edit fails ``--check``, which is
ADR-0042's reversal trigger ("the generated part needs hand edits").

Bounds: the token pass rewrites names, not prose, so a docstring in the async
source that names an async-only type keeps that name in the sync output. Keep
those docstrings runtime-neutral.

Drift-gate::

    kind:       pair
    compares: src/remote_store/_kernel/_async/{driver,kernel}.py ↔ the generated
        src/remote_store/_kernel/_sync/{driver,kernel}.py
    domain:     realization
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import tokenize_rt  # type: ignore[import-untyped]
import unasync  # type: ignore[import-untyped]

ROOT = Path(__file__).resolve().parents[1]
KERNEL = ROOT / "src" / "remote_store" / "_kernel"
SOURCES = ("driver.py", "kernel.py")

# Beyond unasync's defaults (AsyncIterator -> Iterator, __anext__ -> __next__,
# StopAsyncIteration -> StopIteration, ...). Every `class AsyncX` the async
# driver module defines is mapped to `X` on top of these (see _replacements).
_FIXED = {
    "_async": "_sync",
    "aclose": "close",
    "_AsyncKernelCore": "_KernelCore",
}

_CLASS_RE = re.compile(r"^class (Async\w+)\b", re.MULTILINE)
_DOCSTRING_RE = re.compile(r'\A"""(?:.|\n)*?"""\n')


def _replacements(kernel: Path) -> dict[str, str]:
    names = _CLASS_RE.findall((kernel / "_async" / "driver.py").read_text(encoding="utf-8"))
    mapped = {name: name[len("Async") :] for name in names}
    return {**mapped, **_FIXED}


def _ruff(args: list[str], text: str, filename: Path) -> str:
    # The repo's config named explicitly, so a kernel copied outside the tree
    # (the tests do) is formatted exactly as the committed one.
    config = ["--config", str(ROOT / "pyproject.toml")]
    result = subprocess.run(
        [sys.executable, "-m", "ruff", *args, *config, "--stdin-filename", str(filename), "-"],
        input=text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        cwd=ROOT,
        check=False,
    )
    if result.returncode not in (0, 1) or not result.stdout:
        raise RuntimeError(f"ruff {' '.join(args)} failed on {filename.name}: {result.stderr}")
    return result.stdout


def generate(source: Path, target: Path, replacements: dict[str, str]) -> str:
    """The sync text for *source*, as it is committed at *target*."""
    text = source.read_text(encoding="utf-8").replace("\r\n", "\n")
    rule = unasync.Rule("/_async/", "/_sync/", additional_replacements=replacements)
    text = tokenize_rt.tokens_to_src(list(rule._unasync_tokens(tokenize_rt.src_to_tokens(text))))
    header = (
        f'"""Sync twin of ``_async/{source.name}``. GENERATED by ``scripts/gen_sync_kernel.py``: do not edit.\n\n'
        f'Edit ``_async/{source.name}``, then run ``hatch run gen-sync-kernel``.\n"""\n'
    )
    text, count = _DOCSTRING_RE.subn(header, text, count=1)
    if not count:
        raise RuntimeError(f"{source} has no module docstring to replace")
    text = _ruff(["check", "--fix", "--select", "I,F401", "--quiet", "--exit-zero"], text, target)
    return _ruff(["format", "--quiet"], text, target).replace("\r\n", "\n")


def main(argv: list[str] | None = None, kernel: Path = KERNEL) -> int:
    parser = argparse.ArgumentParser(description="Generate the sync contract kernel from the async one.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if a generated file is stale; do not write.")
    args = parser.parse_args(argv)
    replacements = _replacements(kernel)
    stale = []
    for name in SOURCES:
        source, target = kernel / "_async" / name, kernel / "_sync" / name
        expected = generate(source, target, replacements)
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else None
        if current == expected:
            continue
        stale.append(f"_sync/{name}")
        if not args.check:
            target.write_text(expected, encoding="utf-8", newline="\n")
    if args.check:
        if stale:
            print("Generated sync kernel is out of date: " + ", ".join(stale), file=sys.stderr)
            print("Run:  hatch run gen-sync-kernel", file=sys.stderr)
            return 1
        print("Generated sync kernel is up to date.")
        return 0
    print("Updated " + ", ".join(stale) if stale else "Generated sync kernel is already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
